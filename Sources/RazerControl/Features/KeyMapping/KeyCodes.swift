import Foundation
import CoreGraphics

// MARK: - Key Code Mapping
//
// Maps between HID Usage IDs (from USB keyboard reports) and
// macOS CGKeyCode (used by CGEvent / event taps).
// Also provides human-readable names for display.

enum KeyCodeMap {

    // MARK: - HID Usage ID → CGKeyCode

    /// Maps USB HID keyboard usage IDs to macOS virtual keycodes (CGKeyCode)
    static let hidToCG: [UInt8: UInt16] = [
        // Letters A-Z (HID 0x04-0x1D)
        0x04: 0x00, // A
        0x05: 0x0B, // B
        0x06: 0x08, // C
        0x07: 0x02, // D
        0x08: 0x0E, // E
        0x09: 0x03, // F
        0x0A: 0x05, // G
        0x0B: 0x04, // H
        0x0C: 0x22, // I
        0x0D: 0x26, // J
        0x0E: 0x28, // K
        0x0F: 0x25, // L
        0x10: 0x2E, // M
        0x11: 0x2D, // N
        0x12: 0x1F, // O
        0x13: 0x23, // P
        0x14: 0x0C, // Q
        0x15: 0x0F, // R
        0x16: 0x01, // S
        0x17: 0x11, // T
        0x18: 0x20, // U
        0x19: 0x09, // V
        0x1A: 0x0D, // W
        0x1B: 0x07, // X
        0x1C: 0x10, // Y
        0x1D: 0x06, // Z

        // Numbers 1-0 (HID 0x1E-0x27)
        0x1E: 0x12, // 1
        0x1F: 0x13, // 2
        0x20: 0x14, // 3
        0x21: 0x15, // 4
        0x22: 0x17, // 5
        0x23: 0x16, // 6
        0x24: 0x1A, // 7
        0x25: 0x1C, // 8
        0x26: 0x19, // 9
        0x27: 0x1D, // 0

        // Special keys
        0x28: 0x24, // Return
        0x29: 0x35, // Escape
        0x2A: 0x33, // Backspace
        0x2B: 0x30, // Tab
        0x2C: 0x31, // Space

        // Symbols
        0x2D: 0x1B, // - (minus)
        0x2E: 0x18, // = (equal)
        0x2F: 0x21, // [ (left bracket)
        0x30: 0x1E, // ] (right bracket)
        0x31: 0x2A, // \ (backslash)
        0x33: 0x29, // ; (semicolon)
        0x34: 0x27, // ' (quote)
        0x35: 0x32, // ` (grave accent)
        0x36: 0x2B, // , (comma)
        0x37: 0x2F, // . (period)
        0x38: 0x2C, // / (slash)

        // Caps Lock
        0x39: 0x39,

        // Function keys F1-F12
        0x3A: 0x7A, // F1
        0x3B: 0x78, // F2
        0x3C: 0x63, // F3
        0x3D: 0x76, // F4
        0x3E: 0x60, // F5
        0x3F: 0x61, // F6
        0x40: 0x62, // F7
        0x41: 0x64, // F8
        0x42: 0x65, // F9
        0x43: 0x6D, // F10
        0x44: 0x67, // F11
        0x45: 0x6F, // F12

        // F13-F20 (used for macro key remaps)
        0x68: 0x69, // F13 (M1)
        0x69: 0x6B, // F14 (M2)
        0x6A: 0x71, // F15 (M3)
        0x6B: 0x6A, // F16 (M4)
        0x6C: 0x40, // F17 (M5)
        0x6D: 0x4F, // F18 (M6)
        0x6E: 0x50, // F19 (M7)
        0x6F: 0x5A, // F20 (M8)

        // Navigation
        0x46: 0x69, // Print Screen → F13
        0x47: 0x6B, // Scroll Lock → F14
        0x48: 0x71, // Pause → F15
        0x49: 0x72, // Insert
        0x4A: 0x73, // Home
        0x4B: 0x74, // Page Up
        0x4C: 0x75, // Delete Forward
        0x4D: 0x77, // End
        0x4E: 0x79, // Page Down

        // Arrow keys
        0x4F: 0x7C, // Right
        0x50: 0x7B, // Left
        0x51: 0x7D, // Down
        0x52: 0x7E, // Up

        // Numpad
        0x53: 0x47, // Num Lock
        0x54: 0x4B, // Numpad /
        0x55: 0x43, // Numpad *
        0x56: 0x4E, // Numpad -
        0x57: 0x45, // Numpad +
        0x58: 0x4C, // Numpad Enter
        0x59: 0x53, // Numpad 1
        0x5A: 0x54, // Numpad 2
        0x5B: 0x55, // Numpad 3
        0x5C: 0x56, // Numpad 4
        0x5D: 0x57, // Numpad 5
        0x5E: 0x58, // Numpad 6
        0x5F: 0x59, // Numpad 7
        0x60: 0x5B, // Numpad 8
        0x61: 0x5C, // Numpad 9
        0x62: 0x52, // Numpad 0
        0x63: 0x41, // Numpad .

        // Modifiers
        0xE0: 0x3B, // Left Control
        0xE1: 0x38, // Left Shift
        0xE2: 0x3A, // Left Alt/Option
        0xE3: 0x37, // Left GUI/Command
        0xE4: 0x3E, // Right Control
        0xE5: 0x3C, // Right Shift
        0xE6: 0x3D, // Right Alt/Option (AltGr)
        0xE7: 0x36, // Right GUI/Command
    ]

    // MARK: - CGKeyCode → Name

    static func cgKeyName(_ code: UInt16) -> String {
        cgKeyNames[code] ?? "Key \(code)"
    }

    private static let cgKeyNames: [UInt16: String] = [
        0x00: "A", 0x01: "S", 0x02: "D", 0x03: "F", 0x04: "H",
        0x05: "G", 0x06: "Z", 0x07: "X", 0x08: "C", 0x09: "V",
        0x0B: "B", 0x0C: "Q", 0x0D: "W", 0x0E: "E", 0x0F: "R",
        0x10: "Y", 0x11: "T", 0x12: "1", 0x13: "2", 0x14: "3",
        0x15: "4", 0x16: "6", 0x17: "5", 0x18: "=", 0x19: "9",
        0x1A: "7", 0x1B: "-", 0x1C: "8", 0x1D: "0", 0x1E: "]",
        0x1F: "O", 0x20: "U", 0x21: "[", 0x22: "I", 0x23: "P",
        0x24: "Return", 0x25: "L", 0x26: "J", 0x27: "'", 0x28: "K",
        0x29: ";", 0x2A: "\\", 0x2B: ",", 0x2C: "/", 0x2D: "N",
        0x2E: "M", 0x2F: ".", 0x30: "Tab", 0x31: "Space", 0x32: "`",
        0x33: "Backspace", 0x35: "Esc",
        0x36: "Right Cmd", 0x37: "Cmd", 0x38: "Shift", 0x39: "Caps Lock",
        0x3A: "Option", 0x3B: "Control", 0x3C: "Right Shift",
        0x3D: "Right Option", 0x3E: "Right Control",
        0x40: "F17", 0x41: "Numpad .",
        0x43: "Numpad *", 0x45: "Numpad +", 0x47: "Num Lock",
        0x4B: "Numpad /", 0x4C: "Numpad Enter", 0x4E: "Numpad -",
        0x4F: "F18", 0x50: "F19", 0x51: "Numpad =",
        0x52: "Numpad 0", 0x53: "Numpad 1", 0x54: "Numpad 2",
        0x55: "Numpad 3", 0x56: "Numpad 4", 0x57: "Numpad 5",
        0x58: "Numpad 6", 0x59: "Numpad 7", 0x5A: "F20",
        0x5B: "Numpad 8", 0x5C: "Numpad 9",
        0x60: "F5", 0x61: "F6", 0x62: "F7", 0x63: "F3",
        0x64: "F8", 0x65: "F9", 0x67: "F11", 0x69: "F13",
        0x6A: "F16", 0x6B: "F14", 0x6D: "F10", 0x6F: "F12",
        0x71: "F15", 0x72: "Insert", 0x73: "Home", 0x74: "Page Up",
        0x75: "Delete", 0x77: "End", 0x78: "F2", 0x79: "Page Down",
        0x7A: "F1", 0x7B: "Left", 0x7C: "Right", 0x7D: "Down", 0x7E: "Up",
        0x76: "F4",
    ]

    // MARK: - HID → Name (for display in keyboard layout)

    static func hidKeyName(_ code: UInt8) -> String {
        if let cgKey = hidToCG[code] {
            return cgKeyName(cgKey)
        }
        return String(format: "0x%02X", code)
    }
}
